export const getWomensMajorSectionBySlug = (slug: string): MajorSection | undefined => {
  const norm = slug.toLowerCase().trim();
  return WOMENS_FASHION_MAJOR_SECTIONS.find(
    (s) => s.slug.toLowerCase() === norm || s.aliases?.some((a) => a.toLowerCase() === norm)
  );
};

export const getWomensSubcategoryBySlug = (
  sectionSlug: string,
  subcategorySlug: string
): SubcategoryItem | undefined => {
  const normSection = sectionSlug.toLowerCase().trim();
  const normItem = subcategorySlug.toLowerCase().trim();

  const list = WOMENS_SECTION_SUBCATEGORIES_MAP[normSection];
  if (!list) return undefined;

  const found = list.find(
    (sub) =>
      sub.slug.toLowerCase() === normItem ||
      sub.aliases?.some((a) => a.toLowerCase() === normItem)
  );

  if (found) return found;

  // Check singular/plural variation
  const altSlug = normItem.endsWith('s') ? normItem.slice(0, -1) : `${normItem}s`;
  const altFound = list.find(
    (sub) =>
      sub.slug.toLowerCase() === altSlug ||
      sub.aliases?.some((a) => a.toLowerCase() === altSlug)
  );

  return altFound;
};
