export function getMajorSectionBySlug(slug: string): MajorSection | undefined {
  const norm = slug.toLowerCase().trim();
  return MENS_FASHION_MAJOR_SECTIONS.find(
    (s) => s.slug.toLowerCase() === norm || s.aliases?.some((a) => a.toLowerCase() === norm)
  );
}

export function getSubcategoryBySlug(
  sectionSlug: string,
  itemSlug: string
): SubcategoryItem | undefined {
  const normSection = sectionSlug.toLowerCase().trim();
  const normItem = itemSlug.toLowerCase().trim();

  const subList = SECTION_SUBCATEGORIES_MAP[normSection];
  if (!subList) return undefined;

  const found = subList.find(
    (item) =>
      item.slug.toLowerCase() === normItem ||
      item.aliases?.some((a) => a.toLowerCase() === normItem)
  );

  if (found) return found;

  // Check singular/plural variation
  const altSlug = normItem.endsWith('s') ? normItem.slice(0, -1) : `${normItem}s`;
  const altFound = subList.find(
    (item) =>
      item.slug.toLowerCase() === altSlug ||
      item.aliases?.some((a) => a.toLowerCase() === altSlug)
  );

  return altFound;
}
